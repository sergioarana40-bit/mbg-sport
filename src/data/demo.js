// Une productos con el nombre de su categoría (como haría un JOIN en Supabase).
export function withCategoryNames(products, categories) {
  const map = Object.fromEntries(categories.map((c) => [c.id, c.name]))
  return products.map((p) => ({ ...p, category_name: map[p.category_id] || 'General' }))
}
